// switch case => 6:47:00

const month = 3
switch (month) {
    case 1:
        console.log("January")
        break;
    case 2:
        console.log("feb")
        break;
    case 3:
        console.log("mar")
        break;
    case 4:
        console.log("apr")
        break;

    default:
        console.log(" default case none ")
        break;
}
